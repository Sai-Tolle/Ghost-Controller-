#!/usr/bin/env python3
"""Generate UI artifacts from design/tokens.json — the single source of truth.

Outputs:
    qml/theme/Token.qml            FLAT QML QtObject: every leaf is a
                                   top-level readonly property with a dotted
                                   name like `color_ui_text`, `typography_size_md`.
                                   This keeps bindings reliable when Token is
                                   exposed as a QML context property.
    web/tokens/ghost-tokens.css    CSS custom properties (--gh-*)
    web/tokens/tailwind.ghost.json Tailwind v3 theme.extend fragment

The same tokens.json is consumed by the Figma plugin (design/figma-plugin),
keeping Figma, QML and the web HUD in lockstep. Run after any token change:

    python tools/gen_tokens.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
QML_OUT = ROOT / "qml" / "theme" / "Token.qml"
CSS_OUT = ROOT / "web" / "tokens" / "ghost-tokens.css"
TW_OUT = ROOT / "web" / "tokens" / "tailwind.ghost.json"


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def qml_type(value) -> str:
    if isinstance(value, str) and value.startswith("#"):
        return "color"
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, (int, float)):
        return "real"
    return "string"


def qml_literal(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value)
    return str(value)


def collect_leaves(nodes: dict, prefix: str, out: list[tuple[str, str, str]]):
    """Flatten a nested dict into (property_name, qml_type, qml_literal)."""
    for key, value in nodes.items():
        name = f"{prefix}_{key}" if prefix else key
        if isinstance(value, dict):
            collect_leaves(value, name, out)
        else:
            out.append((name, qml_type(value), qml_literal(value)))


def emit_qml_flat(leaves: list[tuple[str, str, str]], indent: int,
                  themed: dict[str, dict[str, str]] | None = None) -> list[str]:
    """One readonly property per leaf. A leaf overridden by a theme becomes a
    binding on `theme`, so switching Token.theme restyles the UI live."""
    pad = " " * indent
    lines: list[str] = []
    for name, typ, lit in leaves:
        overrides = {t: v[name] for t, v in (themed or {}).items() if name in v}
        expr = lit
        for theme_name, value in overrides.items():
            expr = f'theme === "{theme_name}" ? {value} : {expr}'
        lines.append(f"{pad}readonly property {typ} {name}: {expr}")
    return lines


def css_value(value):
    """tokens.json uses Qt's #AARRGGBB for translucent colors; CSS reads
    8-digit hex as #RRGGBBAA, so emit those as rgba()."""
    if isinstance(value, str) and re.fullmatch(r"#[0-9A-Fa-f]{8}", value):
        a, r, g, b = (int(value[i:i + 2], 16) for i in (1, 3, 5, 7))
        return f"rgba({r},{g},{b},{round(a / 255, 3)})"
    return value


def emit_css(nodes: dict, prefix: str) -> list[str]:
    lines: list[str] = []
    for key, value in nodes.items():
        name = f"{prefix}-{kebab(key)}"
        if isinstance(value, dict):
            lines.extend(emit_css(value, name))
        else:
            lines.append(f"  --{name}: {css_value(value)};")
    return lines


def emit_tailwind(nodes: dict) -> dict:
    out: dict = {}
    for key, value in nodes.items():
        out[key] = emit_tailwind(value) if isinstance(value, dict) else value
    return out


def main() -> int:
    if not TOKENS.exists():
        print(f"error: {TOKENS} not found — run from the repo root", file=sys.stderr)
        return 1
    data = json.loads(TOKENS.read_text())
    groups = {k: v for k, v in data.items() if k not in ("meta", "themes")}
    themes = data.get("themes", {})

    # --- QML: FLAT QtObject, one readonly property per leaf ---------------
    leaves: list[tuple[str, str, str]] = []
    collect_leaves(groups, "", leaves)
    known = {name for name, _, _ in leaves}
    themed: dict[str, dict[str, str]] = {}
    for theme_name, tree in themes.items():
        tl: list[tuple[str, str, str]] = []
        collect_leaves(tree, "", tl)
        unknown = [n for n, _, _ in tl if n not in known]
        if unknown:
            print(f"error: theme '{theme_name}' overrides unknown tokens: {unknown}", file=sys.stderr)
            return 1
        themed[theme_name] = {n: lit for n, _, lit in tl}

    qml = [
        "// GENERATED by tools/gen_tokens.py from design/tokens.json — do not edit.",
        "import QtQuick",
        "",
        "QtObject {",
        "    // Active theme: \"dark\" (default) or a key of tokens.json `themes`.",
        "    // Set by app/bridge/theme.py from the operator's preference.",
        '    property string theme: "dark"',
    ]
    qml.extend(emit_qml_flat(leaves, 4, themed))
    qml += [
        "",
        "    // Operator-chosen ink for marks drawn over live video (heading tape,",
        "    // ladder, tapes, bore-sight). Defaults to the token; app/bridge/theme.py",
        "    // overrides it from the saved HUD colour (white is not always visible).",
        "    property color hudInk: color_hud_text",
        "    property color hudInkShadow: color_hud_textShadow",
    ]
    qml.append("}")
    qml.append("")

    QML_OUT.parent.mkdir(parents=True, exist_ok=True)
    QML_OUT.write_text("\n".join(qml))

    # qmldir (kept for backward compat; the desktop build now exposes Token as
    # a context property, but the file is still registered in case any tooling
    # or future QML import path relies on it).
    qmldir = QML_OUT.parent / "qmldir"
    if not qmldir.exists() or "Token.qml" not in qmldir.read_text():
        qmldir.write_text("singleton Token 1.0 Token.qml\n")

    # --- CSS -------------------------------------------------------------
    css = [
        "/* GENERATED by tools/gen_tokens.py from design/tokens.json — do not edit. */",
        ":root {",
        *emit_css(groups, "gh"),
        "}",
        "",
    ]
    for theme_name, tree in themes.items():
        css += [f'[data-theme="{theme_name}"] {{', *emit_css(tree, "gh"), "}", ""]
    CSS_OUT.parent.mkdir(parents=True, exist_ok=True)
    CSS_OUT.write_text("\n".join(css))

    # --- Tailwind --------------------------------------------------------
    TW_OUT.parent.mkdir(parents=True, exist_ok=True)
    TW_OUT.write_text(json.dumps({"theme": {"extend": emit_tailwind(groups)}}, indent=2) + "\n")

    print(f"tokens: {len(leaves)} leaves -> {QML_OUT.relative_to(ROOT)}, "
          f"{CSS_OUT.relative_to(ROOT)}, {TW_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
